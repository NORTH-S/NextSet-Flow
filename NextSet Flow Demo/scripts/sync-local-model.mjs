// Import the frozen standalone artifact; never retrain or change its thresholds.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../NextSet Flow Intent Model');
const digest = (value) => createHash('sha256').update(value).digest('hex');
const [modelBytes, runtimeBytes, selectionText, metricsText] = await Promise.all([
  readFile(resolve(source, 'model/model.json')), readFile(resolve(source, 'runtime/classifier.js')),
  readFile(resolve(source, 'model/selection.json'), 'utf8'), readFile(resolve(source, 'reports/metrics.json'), 'utf8'),
]);
const model = JSON.parse(modelBytes.toString('utf8'));
const selection = JSON.parse(selectionText), metrics = JSON.parse(metricsText);
const modelSHA256 = digest(modelBytes);
assert.equal(modelSHA256, selection.modelSHA256, 'The selected model artifact changed');
assert.equal(modelSHA256, metrics.modelSHA256, 'Evaluation does not match this artifact');
assert.equal(model.format, 'nextset-tfidf-logreg-v1');
assert.deepEqual([...model.labels].sort(), ['clarify', 'full', 'legs', 'pull', 'push', 'unsupported', 'upper']);
for (const key of ['minConfidence', 'minMargin', 'minKnownFraction']) assert.equal(model.abstention[key], selection.chosenPolicy[key], `Threshold changed: ${key}`);
const info = {
  version: model.version, modelSHA256, runtimeSHA256: digest(runtimeBytes), modelBytes: modelBytes.length,
  modelFormat: model.format, labels: model.labels, task: 'Workout-focus classification only',
  seedRows: model.metadata.seedRows, trainingRowsAfterAugmentation: model.metadata.trainingRowsAfterAugmentation,
  evaluation: { rows: metrics.testCount, rawAccuracy: metrics.raw.accuracy, macroF1: metrics.raw.macroF1, dataType: metrics.dataType },
  abstention: model.abstention, source: '../NextSet Flow Intent Model',
};
await writeFile(resolve(root, 'dist/trained-classifier.js'), runtimeBytes);
await writeFile(resolve(root, 'dist/trained-model.js'), `// Generated by scripts/sync-local-model.mjs from the frozen trained artifact.\nexport const LOCAL_MODEL_INFO = ${JSON.stringify(info)};\nexport const TRAINED_MODEL = ${modelBytes.toString('utf8')};\n`, 'utf8');
await writeFile(resolve(root, 'dist/local-model-info.json'), JSON.stringify(info, null, 2) + '\n', 'utf8');
console.log(JSON.stringify({ modelSHA256, runtimeSHA256: info.runtimeSHA256, bytes: modelBytes.length, thresholdsPreserved: true }));
